section "12. DEPENDENCY TREE"
# ─────────────────────────────────────────────────────────────────────────────

print ""
print "  Cluster: ${CL_NAME}  [${CL_STATE}]"
print "  │"

for NODE in $(${CLMGR} query node 2>/dev/null); do
    print "  ├── Node: ${NODE}"
    for NET in $(${CLMGR} query network 2>/dev/null); do
        print "  │   ├── Network: ${NET}"
        # show interfaces on this node + this network
        for IFACE in $(${CLMGR} query interface 2>/dev/null); do
            I_RAW=$(${CLMGR} query interface "${IFACE}" 2>/dev/null)
            I_NODE=$(qval NODE    "${I_RAW}")
            I_NET=$(qval NETWORK  "${I_RAW}")
            I_IP=$(qval IPADDR    "${I_RAW}")
            I_TYPE=$(qval TYPE    "${I_RAW}")
            I_STATE=$(qval STATE  "${I_RAW}")
            if [ "${I_NODE}" = "${NODE}" ] && [ "${I_NET}" = "${NET}" ]; then
                print "  │   │   └── [${I_TYPE}] ${IFACE}  ${I_IP}  (${I_STATE})"
            fi
        done
    done
done

print "  │"
print "  └── Resource Groups:"

for RG in $(${CLMGR} query resource_group 2>/dev/null); do
    RG_RAW=$(${CLMGR} query resource_group "${RG}" 2>/dev/null)
    RG_STATE=$(qval STATE        "${RG_RAW}")
    RG_NODE=$(qval CURRENT_NODE  "${RG_RAW}")
    RG_APPS=$(qval APPLICATIONS  "${RG_RAW}")
    RG_SVC=$(qval SERVICE_LABEL  "${RG_RAW}")
    RG_VG=$(qval VOLUME_GROUP    "${RG_RAW}")
    print "      ├── RG: ${RG}  [${RG_STATE} on ${RG_NODE}]"
    print "      │   ├── Service IP   : ${RG_SVC}"
    # Service IP details
    S_RAW=$(${CLMGR} query service_ip "${RG_SVC}" 2>/dev/null)
    S_IP=$(qval IPADDR "${S_RAW}")
    print "      │   │     └── IP: ${S_IP}"
    print "      │   ├── Application  : ${RG_APPS}"
    # App details
    A_RAW=$(${CLMGR} query application "${RG_APPS}" 2>/dev/null)
    A_START=$(qval STARTSCRIPT "${A_RAW}")
    A_STOP=$(qval STOPSCRIPT   "${A_RAW}")
    print "      │   │     ├── Start: ${A_START}"
    print "      │   │     └── Stop : ${A_STOP}"
    print "      │   └── Volume Group : ${RG_VG}"
    # VG → LV → FS
    lsvg -l "${RG_VG}" 2>/dev/null | grep -v "^${RG_VG}:" | grep -v "^LV NAME" | \
    while read LV TYPE LPS PPS PVS LV_STATE MP; do
        [ -z "${LV}" ] && continue
        print "      │         ├── LV: ${LV}  [${LV_STATE}]  → ${MP}"
    done
    # PVs
    lsvg -p "${RG_VG}" 2>/dev/null | grep -v "^${RG_VG}:" | grep -v "^PV_NAME" | \
    while read PV PV_STATE TOTAL FREE DIST; do
        [ -z "${PV}" ] && continue
        print "      │         └── PV: ${PV}  [${PV_STATE}]  Total:${TOTAL}PP  Free:${FREE}PP"
    done
    print "      │"
done

